#!/usr/bin/env bash
# Regenerate src/i18n/strings.ts from the translation tables (t1–t5.py) and strings.json.
# Needs: python3, node, and `npm install --no-save opencc-js@1.0.5` once in the project.
set -e
cd "$(dirname "$0")"
python3 - <<'PY'
import json, importlib.util, re, glob
a = json.load(open('strings.json'))
hant = {}
for k in ['t1', 't2', 't3', 't4', 't5']:
    spec = importlib.util.spec_from_file_location(k, f'{k}.py'); m = importlib.util.module_from_spec(spec); spec.loader.exec_module(m)
    for i, v in getattr(m, 'T', {}).items(): hant[a[i]] = v
    for e, v in getattr(m, 'EXTRA', {}).items(): hant[e] = v
hant = {re.sub(r'\s+', ' ', k).strip(): v for k, v in hant.items()}
chars = set()
for f in glob.glob('../src/**/*.ts*', recursive=True):
    if f.endswith('strings.ts'): continue
    chars |= set(re.findall(r'[一-鿿]', open(f).read()))
for v in hant.values(): chars |= set(re.findall(r'[一-鿿]', v))
json.dump(hant, open('hant.json', 'w'), ensure_ascii=False)
json.dump(sorted(chars), open('chars.json', 'w'), ensure_ascii=False)
print('entries', len(hant))
PY
cd .. && node -e "
const O=require('opencc-js');const fs=require('fs');const c=O.Converter({from:'hk',to:'cn'});
const hant=JSON.parse(fs.readFileSync('i18n-tools/hant.json','utf8'));
const hans={};for(const k in hant) hans[k]=c(hant[k]);
const chars=JSON.parse(fs.readFileSync('i18n-tools/chars.json','utf8'));
const map={};for(const ch of chars){const s=c(ch); if(s!==ch) map[ch]=s;}
fs.writeFileSync('src/i18n/strings.ts','// Generated by i18n-tools/regen.sh: English source text → Traditional (zh-Hant) and Simplified (zh-Hans) Chinese.\n'+
'export const HANT: Record<string, string> = '+JSON.stringify(hant)+';\n'+
'export const HANS: Record<string, string> = '+JSON.stringify(hans)+';\n'+
'// Character map for Chinese text that is already in the source (bilingual labels, sample notices, pattern text).\n'+
'export const T2S: Record<string, string> = '+JSON.stringify(map)+';\n');
console.log('t2s',Object.keys(map).length);"
